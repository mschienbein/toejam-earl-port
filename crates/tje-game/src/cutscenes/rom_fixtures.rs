//! Opt-in ROM checker for the cutscenes, speech and ship W0 leaves.
//! Run through cutscenes/fixtures/Cargo.toml; retail inputs and metrics stay private.

use std::{fs, path::PathBuf};
use tje_game::{FunctionId, ids};
use tje_host::{Host, Mode, hooks::HookRegistry, input::InputScript};
use tje_mem::{Revision, ram};

const SUBSYSTEMS: &[&str] = &["cutscenes", "speech", "ship"];
const FRAMES: u64 = 10_000;

fn check(host: &mut Host, id: FunctionId, arguments: &[u32]) -> u32 {
    host.check_fixture(id.metadata().address(host.revision()), arguments)
        .unwrap_or_else(|error| panic!("{} {arguments:08x?}: {error}", id.metadata().name))
}

fn emit(host: &Host, session: &str, natural: serde_json::Value) {
    let evidence = serde_json::json!({
        "revision": host.revision().name(),
        "session": session,
        "frames": host.frame_count(),
        "whole_session_timed_reference_comparison": true,
        "natural": natural,
        "with_labelled_live_state_fixtures": host.checks,
        "measurements": host.measurements,
    });
    println!("CUTSCENES_COVERAGE {evidence}");
    if let Some(directory) = std::env::var_os("TJE_CUTSCENES_METRICS_DIR") {
        let path =
            PathBuf::from(directory).join(format!("{}-{session}.json", host.revision().name()));
        fs::write(path, serde_json::to_string_pretty(&evidence).unwrap()).unwrap();
    }
}

fn run_session(revision: Revision, script: &InputScript) -> Host {
    let key = match revision {
        Revision::Rev02 => "TJE_REV02_ROM",
        Revision::Rev00 => "TJE_REV00_ROM",
    };
    let rom = fs::read(std::env::var_os(key).unwrap_or_else(|| panic!("set {key}"))).unwrap();
    let registry = HookRegistry::filtered(revision, SUBSYSTEMS, &[]).unwrap();
    let mut checked = Host::new(&rom, Mode::Check, registry.clone()).unwrap();
    let mut reference = Host::new(&rom, Mode::Reference, registry).unwrap();
    for frame in 0..FRAMES {
        let a = checked.run_frame(script.at(frame)).unwrap();
        let b = reference.run_frame(script.at(frame)).unwrap();
        assert_eq!(
            a.frame_counter, b.frame_counter,
            "{revision:?} counter frame {frame}"
        );
        assert_eq!(a.ram, b.ram, "{revision:?} whole RAM frame {frame}");
        assert_eq!(a.vdp, b.vdp, "{revision:?} VDP frame {frame}");
        assert_eq!(a.writes, b.writes, "{revision:?} writes frame {frame}");
        assert_eq!(a.idle_random_draws, b.idle_random_draws);
        assert_eq!(a.lag_events, b.lag_events);
        assert!(
            a.audio_samples.iter().flatten().map(|v| v.to_bits()).eq(b
                .audio_samples
                .iter()
                .flatten()
                .map(|v| v.to_bits())),
            "{revision:?} audio frame {frame}"
        );
        let (a, a_size) = checked.frame_buffer();
        let (b, b_size) = reference.frame_buffer();
        assert_eq!(a_size, b_size);
        assert_eq!(
            &a[..a_size.len() as usize],
            &b[..b_size.len() as usize],
            "{revision:?} pixels frame {frame}"
        );
    }
    assert_eq!(checked.checks.mismatches, 0);
    assert!(checked.checks.uninitialized_stack_reads.is_empty());
    checked
}

/// These inputs are authored boundary cases on a fork of live gameplay RAM.
/// They are not claimed to have been generated by the ordinary session.
fn live_state_fixtures(host: &mut Host) {
    let revision = host.revision();
    let buffer = ram::g_sprite_tile_upload_buffer(revision).address();
    let offset = ram::g_sprite_tile_buffer_offset(revision);
    for byte in 0..256_u32 {
        host.context().write_u8(buffer + 512 + byte, byte as u8);
        host.context().write_u8(buffer + byte, byte as u8);
    }
    for count in [-2047_i16, -1, 0, 1, 8, 1024, 2048] {
        offset.write(&mut host.context(), 0);
        check(
            host,
            ids::CUTSCENE_APPEND_REMAPPED_FONT_TILES,
            &[buffer + 512, count as i32 as u32],
        );
        check(host, ids::FILL_SPRITE_OPAQUE_PIXELS, &[count as i32 as u32]);
    }
    offset.write(&mut host.context(), 1);
    host.context().write_u8(buffer, 0xbb);
    check(host, ids::CUTSCENE_APPEND_REMAPPED_FONT_TILES, &[buffer, 1]);
    // A high-bit offset must be zero-extended, not treated as a signed short.
    offset.write(&mut host.context(), 0x8000);
    check(
        host,
        ids::CUTSCENE_APPEND_REMAPPED_FONT_TILES,
        &[buffer + 512, 0],
    );
    check(host, ids::FILL_SPRITE_OPAQUE_PIXELS, &[0]);

    for (slots, id) in [
        (
            ram::g_intro_large_player_part_entities(revision).cast::<u8>(),
            ids::INTRO_SET_LARGE_PLAYER_PART_SEQUENCE,
        ),
        (
            ram::g_intro_driving_part_entities(revision).cast::<u8>(),
            ids::INTRO_SET_DRIVING_PART_SEQUENCE,
        ),
    ] {
        for index in [-1_i16, 0, 2, 7, 8] {
            slots.offset(i32::from(index)).write(&mut host.context(), 8);
            for period in [0, 1, 127, 128, 255, 0x180] {
                check(host, id, &[index as i32 as u32, 0x12345678, period]);
            }
        }
    }
    for (first, second) in [(0, 0), (0, 7), (6, 0), (6, 7)] {
        ram::g_ending_player1_entity(revision).write(&mut host.context(), first);
        ram::g_ending_player2_entity(revision).write(&mut host.context(), second);
        for frame in [i8::MIN, -1, 0, i8::MAX] {
            ram::g_player_info(revision)
                .at(0)
                .frame()
                .write(&mut host.context(), frame);
            ram::g_player_info(revision)
                .at(6)
                .frame()
                .write(&mut host.context(), frame);
            check(host, ids::ENDING_GET_FIRST_PLAYER_ANIMATION_FRAME, &[]);
        }
    }
    for flags in [0, 0x40, 0xff] {
        for index in 0..10 {
            let handle = if index == 0 { 0 } else { (index + 6) as u8 };
            ram::g_intro_component_entities(revision)
                .at(index)
                .write(&mut host.context(), handle);
            ram::g_player_info(revision)
                .at(i32::from(handle))
                .behavior_flags()
                .write(&mut host.context(), flags);
        }
        check(host, ids::INTRO_REVEAL_FRAME_ENTITIES, &[]);
    }
    for (ship, exhaust) in [(6, 7), (6, 6), (0, 0)] {
        ram::g_cutscene_rocketship_entity(revision).write(&mut host.context(), ship);
        ram::g_cutscene_rocketship_exhaust_entity(revision).write(&mut host.context(), exhaust);
        for x in [i16::MIN, -61, -60, -59, 0, i16::MAX] {
            ram::g_player_info(revision)
                .at(i32::from(ship))
                .x()
                .write(&mut host.context(), x);
            ram::g_player_info(revision)
                .at(i32::from(exhaust))
                .x()
                .write(&mut host.context(), x);
            for distance in [0, 1, 3, 0x10001, i32::MIN as u32, i32::MAX as u32] {
                check(host, ids::CUTSCENE_MOVE_ROCKETSHIP_PAIR_LEFT, &[distance]);
            }
        }
        for (x, y) in [(0, 0), (0x12348000, 0xffff7fff), (u32::MAX, 0x80000000)] {
            check(host, ids::CUTSCENE_POSITION_ROCKETSHIP_PAIR, &[x, y]);
        }
    }
    for handle in [0, 6] {
        ram::g_ending_pose_composite_entity(revision).write(&mut host.context(), handle);
        let entity = ram::g_player_info(revision).at(i32::from(handle));
        entity.tile().write(&mut host.context(), 0x1234);
        entity.draw_flags().write(&mut host.context(), 0x07);
        for frame in [i16::MIN, -1, 0, 1, 21, 0x3fff, 0x4000, i16::MAX] {
            for (x, y) in [(0, 0), (i16::MIN, i16::MAX), (i16::MAX, i16::MIN)] {
                check(
                    host,
                    ids::ENDING_SET_POSE_COMPOSITE,
                    &[frame as i32 as u32, x as i32 as u32, y as i32 as u32],
                );
            }
        }
        for (id, slot) in [
            (
                ids::ENDING_POSITION_SIX_PIECE_COMPOSITE,
                ram::g_ending_six_piece_composite_entity(revision),
            ),
            (
                ids::ENDING_POSITION_RIGHT_OFFSET_COMPOSITE,
                ram::g_ending_right_offset_composite_entity(revision),
            ),
            (
                ids::INTRO_POSITION_FALLING_ROCKETSHIP,
                ram::g_intro_falling_rocketship_entity(revision),
            ),
        ] {
            slot.write(&mut host.context(), handle);
            for (x, y) in [(0, 0), (i16::MIN, i16::MAX), (i16::MAX, i16::MIN)] {
                check(host, id, &[x as i32 as u32, y as i32 as u32]);
            }
        }
        ram::g_ending_elevated_three_piece_composite_entity(revision)
            .write(&mut host.context(), handle);
        entity.sprite_ready().write(&mut host.context(), -1);
        check(host, ids::ENDING_RESTART_ELEVATED_COMPOSITE_SEQUENCE, &[]);
    }

    for slot in 0..4 {
        ram::g_speech_bubble_entities(revision)
            .at(slot)
            .write(&mut host.context(), [0, 6, 7, 127][slot as usize]);
    }
    for object in [i16::MIN, -1, 0, 1, 5, 6, 7, 39, 127, 128, i16::MAX] {
        check(host, ids::IS_SPEECH_BUBBLE_ENTITY, &[object as i32 as u32]);
    }
    check(host, ids::IS_SPEECH_BUBBLE_ENTITY, &[0x10007]);
    for slot in 0..4 {
        ram::g_speech_bubble_entities(revision)
            .at(slot)
            .write(&mut host.context(), 0);
    }
    for slot in 0..2 {
        ram::g_delayed_speech_reply_timers(revision)
            .at(slot)
            .write(&mut host.context(), 0);
    }
    for slot in 0..4 {
        for handle in [-1_i8, 7] {
            ram::g_speech_bubble_entities(revision)
                .at(slot)
                .write(&mut host.context(), handle);
            let bubble = ram::g_player_info(revision).at(i32::from(handle));
            for flags in [0, 1, 8, 0xff] {
                bubble.draw_flags().write(&mut host.context(), flags);
                bubble.owner().write(&mut host.context(), -1);
                for speaker in [-1_i16, 0, 255] {
                    check(host, ids::HAS_SPEAKER_SPEECH, &[speaker as i32 as u32]);
                }
            }
            ram::g_speech_bubble_entities(revision)
                .at(slot)
                .write(&mut host.context(), 0);
        }
    }
    for slot in 0..2 {
        for timer in [-1, 1] {
            ram::g_delayed_speech_reply_timers(revision)
                .at(slot)
                .write(&mut host.context(), timer);
            ram::g_delayed_speech_reply_speakers(revision)
                .at(slot)
                .write(&mut host.context(), -128);
            for speaker in [-128_i16, -1, 0, 128] {
                check(host, ids::HAS_SPEAKER_SPEECH, &[speaker as i32 as u32]);
            }
        }
        ram::g_delayed_speech_reply_timers(revision)
            .at(slot)
            .write(&mut host.context(), 0);
    }
    for value in [i16::MIN, -1, 0, 1, i16::MAX] {
        check(host, ids::SET_NEXT_SPEECH_LIFETIME, &[value as i32 as u32]);
    }
    // Exercise a destination that aliases its own offset word: the original
    // reloads that word after the byte loop before its final ADD.W.
    let offset_alias = offset.address().wrapping_sub(buffer) as u16;
    offset.write(&mut host.context(), offset_alias);
    check(
        host,
        ids::CUTSCENE_APPEND_REMAPPED_FONT_TILES,
        &[buffer + 512, 1],
    );
}

#[test]
#[ignore = "requires both private retail ROMs; 10,000 frames each plus timed references"]
fn gameplay_and_labelled_live_state_fixtures_both_revisions() {
    let script =
        InputScript::parse(include_str!("../../../tje-host/examples/start-game.json")).unwrap();
    for revision in [Revision::Rev02, Revision::Rev00] {
        let mut host = run_session(revision, &script);
        assert!(host.measurements.title_frame.is_some());
        assert!(host.measurements.menu_frame.is_some());
        assert!(host.measurements.game_frame.is_some());
        let natural = serde_json::to_value(&host.checks).unwrap();
        live_state_fixtures(&mut host);
        emit(&host, "gameplay", natural);
        assert_eq!(host.checks.mismatches, 0);
        assert_eq!(host.checks.nested_original_calls, 0);
        assert!(host.checks.uninitialized_stack_reads.is_empty());
        assert!(host.checks.unexercised.is_empty());
    }
}

#[test]
#[ignore = "requires both private retail ROMs; unskipped 10,000-frame intro plus timed references"]
fn unskipped_intro_both_revisions() {
    for revision in [Revision::Rev02, Revision::Rev00] {
        let host = run_session(revision, &InputScript::default());
        assert!(host.measurements.intro_frame.is_some());
        emit(&host, "intro", serde_json::to_value(&host.checks).unwrap());
    }
}
