//! Browser compiler for ROM-specialized, instruction-boundary continuations.
//!
//! Every IR operation becomes WebAssembly integer code, a state load/store, or an
//! ordered bus call. There is no opcode decoder or instruction interpreter in the
//! emitted module. Each original instruction is its own small Wasm function.
//! Modules import the application's memory; their private PC-indexed function
//! table does not occupy or initialize application linear memory.

use std::borrow::Cow;
use std::fmt;

use tje_engine_core::ir::{
    BinaryOp, CompareOp, InstructionIr, Op, Program, StateField, Value, Width,
};
use wasm_encoder::{
    BlockType, CodeSection, ConstExpr, ElementSection, Elements, EntityType, ExportKind,
    ExportSection, Function, FunctionSection, GlobalType, ImportSection, Instruction, MemArg,
    MemoryType, Module, RefType, TableSection, TableType, TypeSection, ValType,
};

#[cfg(target_arch = "wasm32")]
mod browser;
#[cfg(target_arch = "wasm32")]
pub use browser::{BrowserBackend, BrowserError, CompilationMetrics};

#[cfg(all(target_arch = "wasm32", feature = "browser-proof"))]
mod proof;

/// Increment whenever generated code, CPU layout, or imported callback ABI changes.
pub const ENGINE_VERSION: &str = "tje-wasm-2-ssa25";
/// Kept well below browser module limits and checked before returning any bytes.
pub const MAX_MODULE_BYTES: usize = 64 * 1024 * 1024;
/// The cartridge is 1 MiB. Compiled code outside it must not be silently dispatched.
pub const MAX_CODE_ADDRESS: u32 = 1024 * 1024;
/// Bound an individual function independently of the module's total size.
pub const MAX_FUNCTION_BYTES: usize = 256 * 1024;
pub const MAX_VALUES: u32 = 16_384;

const ENTRY_TYPE: u32 = 0;
const READ_TYPE: u32 = 1;
const WRITE_TYPE: u32 = 2;
const OFFSET_TYPE: u32 = 3;
const READ8: u32 = 0;
const READ16: u32 = 1;
const WRITE8: u32 = 2;
const WRITE16: u32 = 3;
const READ_OFFSET: u32 = 4;
const IMPORTED_FUNCTIONS: u32 = 5;
const APP_TABLE: u32 = 0;
const CODE_TABLE: u32 = 1;
const STATE: u32 = 0;
const CONTEXT: u32 = 1;
const EXCEPTION: u32 = 2;
const VALUE_BASE: u32 = 3;

/// Generated bytes are private cartridge-derived data and must never be shipped.
#[derive(Debug)]
pub struct GeneratedModule {
    pub bytes: Vec<u8>,
    pub instruction_count: u32,
    pub table_slots: u32,
    pub largest_function_bytes: usize,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum GenerateError {
    EmptyProgram,
    InvalidPc(u32),
    UnsortedPc(u32),
    InvalidIr { pc: u32, reason: &'static str },
    FunctionTooLarge { pc: u32, bytes: usize },
    ModuleTooLarge(usize),
}

impl fmt::Display for GenerateError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::EmptyProgram => f.write_str("cannot compile an empty instruction program"),
            Self::InvalidPc(pc) => {
                write!(f, "instruction PC {pc:#x} is not an even cartridge address")
            }
            Self::UnsortedPc(pc) => {
                write!(f, "instruction PCs are not strictly increasing at {pc:#x}")
            }
            Self::InvalidIr { pc, reason } => {
                write!(f, "invalid instruction IR at {pc:#x}: {reason}")
            }
            Self::FunctionTooLarge { pc, bytes } => {
                write!(
                    f,
                    "instruction at {pc:#x} needs {bytes} bytes of WebAssembly code"
                )
            }
            Self::ModuleTooLarge(bytes) => {
                write!(f, "WebAssembly module exceeds 64 MiB ({bytes} bytes)")
            }
        }
    }
}
impl std::error::Error for GenerateError {}

/// Emit a cacheable module whose imports do not depend on memory addresses or
/// application function-table indices. `env.entry_slot` is an immutable i32
/// global selecting one newly reserved slot in the application's function table.
///
/// Imported functions are raw Wasm exports, not JavaScript wrappers:
/// `read8/read16(context,address,ReadKind)->u32`,
/// `write8/write16(context,address,value)`, and `set_read_offset(context,mclk)`.
/// The generated entry has ABI `(state,context,ExceptionOut)->u64`, with cycles
/// in the low 32 bits and exception vector in the high 32 bits.
pub fn generate(program: &Program) -> Result<GeneratedModule, GenerateError> {
    validate(program)?;
    let count = program.instructions.len() as u32;
    let table_slots = (program.instructions.last().unwrap().pc >> 1) + 1;
    let mut module = Module::new();
    let mut types = TypeSection::new();
    types.ty().function([ValType::I32; 3], [ValType::I64]);
    types.ty().function([ValType::I32; 3], [ValType::I32]);
    types.ty().function([ValType::I32; 3], []);
    types.ty().function([ValType::I32; 2], []);
    module.section(&types);

    let mut imports = ImportSection::new();
    imports.import(
        "env",
        "memory",
        EntityType::Memory(MemoryType {
            minimum: 0,
            maximum: None,
            memory64: false,
            shared: false,
            page_size_log2: None,
        }),
    );
    imports.import(
        "env",
        "table",
        EntityType::Table(TableType {
            element_type: RefType::FUNCREF,
            table64: false,
            minimum: 0,
            maximum: None,
            shared: false,
        }),
    );
    imports.import(
        "env",
        "entry_slot",
        EntityType::Global(GlobalType {
            val_type: ValType::I32,
            mutable: false,
            shared: false,
        }),
    );
    imports.import("env", "read8", EntityType::Function(READ_TYPE));
    imports.import("env", "read16", EntityType::Function(READ_TYPE));
    imports.import("env", "write8", EntityType::Function(WRITE_TYPE));
    imports.import("env", "write16", EntityType::Function(WRITE_TYPE));
    imports.import("env", "set_read_offset", EntityType::Function(OFFSET_TYPE));
    module.section(&imports);

    let mut functions = FunctionSection::new();
    for _ in 0..=count {
        functions.function(ENTRY_TYPE);
    }
    module.section(&functions);
    let mut tables = TableSection::new();
    tables.table(TableType {
        element_type: RefType::FUNCREF,
        table64: false,
        minimum: u64::from(table_slots),
        maximum: Some(u64::from(table_slots)),
        shared: false,
    });
    module.section(&tables);
    let mut exports = ExportSection::new();
    exports.export("step", ExportKind::Func, IMPORTED_FUNCTIONS);
    module.section(&exports);

    let mut elements = ElementSection::new();
    elements.active(
        Some(APP_TABLE),
        &ConstExpr::global_get(0),
        Elements::Functions(Cow::Borrowed(&[IMPORTED_FUNCTIONS])),
    );
    // One constant-size segment per instruction; holes remain null and fail closed.
    // No ROM bytes or dispatch data are copied into the app's linear memory.
    for (index, instruction) in program.instructions.iter().enumerate() {
        elements.active(
            Some(CODE_TABLE),
            &ConstExpr::i32_const((instruction.pc >> 1) as i32),
            Elements::Functions(Cow::Borrowed(&[IMPORTED_FUNCTIONS + 1 + index as u32])),
        );
    }
    module.section(&elements);
    let mut code = CodeSection::new();
    code.function(&dispatcher(table_slots));
    let mut largest = 0;
    for instruction in &program.instructions {
        let function = emit_instruction(instruction);
        let size = function.byte_len();
        if size > MAX_FUNCTION_BYTES {
            return Err(GenerateError::FunctionTooLarge {
                pc: instruction.pc,
                bytes: size,
            });
        }
        largest = largest.max(size);
        code.function(&function);
        // Bound intermediate section growth too, not just the finished module.
        if code.byte_len() > MAX_MODULE_BYTES {
            return Err(GenerateError::ModuleTooLarge(code.byte_len()));
        }
    }
    module.section(&code);
    let bytes = module.finish();
    if bytes.len() > MAX_MODULE_BYTES {
        return Err(GenerateError::ModuleTooLarge(bytes.len()));
    }
    Ok(GeneratedModule {
        bytes,
        instruction_count: count,
        table_slots,
        largest_function_bytes: largest,
    })
}

fn memory_arg(offset: u32) -> MemArg {
    MemArg {
        offset: u64::from(offset),
        align: 2,
        memory_index: 0,
    }
}
fn dispatcher(table_slots: u32) -> Function {
    let mut f = Function::new([(1, ValType::I32)]);
    // Reject odd, out-of-range and absent PCs before call_indirect, returning a
    // nonarchitectural sentinel so Backend::execute can report a typed error.
    f.instruction(&Instruction::LocalGet(STATE));
    f.instruction(&Instruction::I32Load(memory_arg(StateField::Pc.offset())));
    f.instruction(&Instruction::LocalTee(3));
    f.instruction(&Instruction::I32Const(1));
    f.instruction(&Instruction::I32And);
    f.instruction(&Instruction::LocalGet(3));
    f.instruction(&Instruction::I32Const((table_slots * 2) as i32));
    f.instruction(&Instruction::I32GeU);
    f.instruction(&Instruction::I32Or);
    f.instruction(&Instruction::If(BlockType::Empty));
    f.instruction(&Instruction::I64Const((u64::from(u32::MAX) << 32) as i64));
    f.instruction(&Instruction::Return);
    f.instruction(&Instruction::End);
    f.instruction(&Instruction::LocalGet(3));
    f.instruction(&Instruction::I32Const(1));
    f.instruction(&Instruction::I32ShrU);
    f.instruction(&Instruction::LocalTee(3));
    f.instruction(&Instruction::TableGet(CODE_TABLE));
    f.instruction(&Instruction::RefIsNull);
    f.instruction(&Instruction::If(BlockType::Empty));
    f.instruction(&Instruction::I64Const((u64::from(u32::MAX) << 32) as i64));
    f.instruction(&Instruction::Return);
    f.instruction(&Instruction::End);
    f.instruction(&Instruction::LocalGet(STATE));
    f.instruction(&Instruction::LocalGet(CONTEXT));
    f.instruction(&Instruction::LocalGet(EXCEPTION));
    f.instruction(&Instruction::LocalGet(3));
    f.instruction(&Instruction::CallIndirect {
        type_index: ENTRY_TYPE,
        table_index: CODE_TABLE,
    });
    f.instruction(&Instruction::End);
    f
}
fn get(f: &mut Function, value: Value) {
    f.instruction(&Instruction::LocalGet(VALUE_BASE + value.0));
}
fn set(f: &mut Function, value: Value) {
    f.instruction(&Instruction::LocalSet(VALUE_BASE + value.0));
}
fn packed_return(f: &mut Function, cycles: Value, vector: u32) {
    get(f, cycles);
    f.instruction(&Instruction::I64ExtendI32U);
    if vector != 0 {
        f.instruction(&Instruction::I64Const((u64::from(vector) << 32) as i64));
        f.instruction(&Instruction::I64Or);
    }
    f.instruction(&Instruction::Return);
}
fn emit_instruction(ir: &InstructionIr) -> Function {
    let mut f = Function::new([(ir.value_count, ValType::I32)]);
    for op in &ir.ops {
        match *op {
            Op::Constant { dst, value } => {
                f.instruction(&Instruction::I32Const(value as i32));
                set(&mut f, dst);
            }
            Op::LoadState { dst, field } => {
                f.instruction(&Instruction::LocalGet(STATE));
                f.instruction(&Instruction::I32Load(memory_arg(field.offset())));
                set(&mut f, dst);
            }
            Op::StoreState { field, value } => {
                f.instruction(&Instruction::LocalGet(STATE));
                get(&mut f, value);
                f.instruction(&Instruction::I32Store(memory_arg(field.offset())));
            }
            Op::Binary { dst, op, lhs, rhs } => {
                if op == BinaryOp::DivideSigned {
                    // Wasm traps on MIN / -1. The IR deliberately wraps instead.
                    get(&mut f, lhs);
                    f.instruction(&Instruction::I32Const(i32::MIN));
                    f.instruction(&Instruction::I32Eq);
                    get(&mut f, rhs);
                    f.instruction(&Instruction::I32Const(-1));
                    f.instruction(&Instruction::I32Eq);
                    f.instruction(&Instruction::I32And);
                    f.instruction(&Instruction::If(BlockType::Result(ValType::I32)));
                    f.instruction(&Instruction::I32Const(i32::MIN));
                    f.instruction(&Instruction::Else);
                    get(&mut f, lhs);
                    get(&mut f, rhs);
                    f.instruction(&Instruction::I32DivS);
                    f.instruction(&Instruction::End);
                } else {
                    get(&mut f, lhs);
                    get(&mut f, rhs);
                    f.instruction(&match op {
                        BinaryOp::Add => Instruction::I32Add,
                        BinaryOp::Subtract => Instruction::I32Sub,
                        BinaryOp::Multiply => Instruction::I32Mul,
                        BinaryOp::And => Instruction::I32And,
                        BinaryOp::Or => Instruction::I32Or,
                        BinaryOp::Xor => Instruction::I32Xor,
                        BinaryOp::ShiftLeft => Instruction::I32Shl,
                        BinaryOp::ShiftRight => Instruction::I32ShrU,
                        BinaryOp::ArithmeticShiftRight => Instruction::I32ShrS,
                        BinaryOp::DivideUnsigned => Instruction::I32DivU,
                        BinaryOp::RemainderUnsigned => Instruction::I32RemU,
                        BinaryOp::RemainderSigned => Instruction::I32RemS,
                        BinaryOp::DivideSigned => unreachable!(),
                    });
                }
                set(&mut f, dst);
            }
            Op::Compare { dst, op, lhs, rhs } => {
                get(&mut f, lhs);
                get(&mut f, rhs);
                f.instruction(&match op {
                    CompareOp::Equal => Instruction::I32Eq,
                    CompareOp::NotEqual => Instruction::I32Ne,
                    CompareOp::UnsignedLess => Instruction::I32LtU,
                    CompareOp::UnsignedLessEqual => Instruction::I32LeU,
                    CompareOp::SignedLess => Instruction::I32LtS,
                    CompareOp::SignedLessEqual => Instruction::I32LeS,
                });
                set(&mut f, dst);
            }
            Op::Select {
                dst,
                condition,
                if_true,
                if_false,
            } => {
                get(&mut f, if_true);
                get(&mut f, if_false);
                get(&mut f, condition);
                f.instruction(&Instruction::Select);
                set(&mut f, dst);
            }
            Op::ReadMemory {
                dst,
                address,
                width,
                kind,
            } => {
                f.instruction(&Instruction::LocalGet(CONTEXT));
                get(&mut f, address);
                f.instruction(&Instruction::I32Const(kind as i32));
                f.instruction(&Instruction::Call(match width {
                    Width::Byte => READ8,
                    Width::Word => READ16,
                }));
                set(&mut f, dst);
            }
            Op::ReadMemoryIf {
                dst,
                condition,
                address,
                width,
                kind,
            } => {
                get(&mut f, condition);
                f.instruction(&Instruction::If(BlockType::Result(ValType::I32)));
                f.instruction(&Instruction::LocalGet(CONTEXT));
                get(&mut f, address);
                f.instruction(&Instruction::I32Const(kind as i32));
                f.instruction(&Instruction::Call(match width {
                    Width::Byte => READ8,
                    Width::Word => READ16,
                }));
                f.instruction(&Instruction::Else);
                f.instruction(&Instruction::I32Const(0));
                f.instruction(&Instruction::End);
                set(&mut f, dst);
            }
            Op::WriteMemory {
                address,
                value,
                width,
            } => {
                f.instruction(&Instruction::LocalGet(CONTEXT));
                get(&mut f, address);
                get(&mut f, value);
                f.instruction(&Instruction::Call(match width {
                    Width::Byte => WRITE8,
                    Width::Word => WRITE16,
                }));
            }
            Op::SetReadOffset { cycles } => {
                f.instruction(&Instruction::LocalGet(CONTEXT));
                get(&mut f, cycles);
                f.instruction(&Instruction::Call(READ_OFFSET));
            }
            Op::ExitIf { condition, exit } => {
                get(&mut f, condition);
                f.instruction(&Instruction::If(BlockType::Empty));
                for (offset, value) in [
                    (0, exit.saved_pc),
                    (4, exit.fault_address),
                    (8, exit.fault_status),
                ] {
                    f.instruction(&Instruction::LocalGet(EXCEPTION));
                    get(&mut f, value);
                    f.instruction(&Instruction::I32Store(memory_arg(offset)));
                }
                packed_return(&mut f, exit.cycles, exit.vector);
                f.instruction(&Instruction::End);
            }
            Op::Finish { cycles } => packed_return(&mut f, cycles, 0),
        }
    }
    f.instruction(&Instruction::Unreachable);
    f.instruction(&Instruction::End);
    f
}

fn validate(program: &Program) -> Result<(), GenerateError> {
    if program.instructions.is_empty() {
        return Err(GenerateError::EmptyProgram);
    }
    let mut previous = None;
    let mut defined = Vec::new();
    for ir in &program.instructions {
        if ir.pc & 1 != 0 || ir.pc >= MAX_CODE_ADDRESS {
            return Err(GenerateError::InvalidPc(ir.pc));
        }
        if previous.is_some_and(|pc| pc >= ir.pc) {
            return Err(GenerateError::UnsortedPc(ir.pc));
        }
        previous = Some(ir.pc);
        let invalid = |reason| GenerateError::InvalidIr { pc: ir.pc, reason };
        if ir.value_count > MAX_VALUES {
            return Err(invalid("too many SSA values"));
        }
        if !matches!(ir.ops.last(), Some(Op::Finish { .. })) {
            return Err(invalid("missing terminal Finish"));
        }
        defined.clear();
        defined.resize(ir.value_count as usize, false);
        for (index, op) in ir.ops.iter().enumerate() {
            let mut inputs = [None; 5];
            let dst = match *op {
                Op::Constant { dst, .. } | Op::LoadState { dst, .. } => Some(dst),
                Op::StoreState { value, .. } | Op::SetReadOffset { cycles: value } => {
                    inputs[0] = Some(value);
                    None
                }
                Op::Binary { dst, lhs, rhs, .. } | Op::Compare { dst, lhs, rhs, .. } => {
                    inputs[..2].copy_from_slice(&[Some(lhs), Some(rhs)]);
                    Some(dst)
                }
                Op::Select {
                    dst,
                    condition,
                    if_true,
                    if_false,
                } => {
                    inputs[..3].copy_from_slice(&[Some(condition), Some(if_true), Some(if_false)]);
                    Some(dst)
                }
                Op::ReadMemory { dst, address, .. } => {
                    inputs[0] = Some(address);
                    Some(dst)
                }
                Op::ReadMemoryIf {
                    dst,
                    condition,
                    address,
                    ..
                } => {
                    inputs[..2].copy_from_slice(&[Some(condition), Some(address)]);
                    Some(dst)
                }
                Op::WriteMemory { address, value, .. } => {
                    inputs[..2].copy_from_slice(&[Some(address), Some(value)]);
                    None
                }
                Op::ExitIf { condition, exit } => {
                    if !(1..=255).contains(&exit.vector) {
                        return Err(invalid("invalid exception vector"));
                    }
                    inputs = [
                        Some(condition),
                        Some(exit.cycles),
                        Some(exit.saved_pc),
                        Some(exit.fault_address),
                        Some(exit.fault_status),
                    ];
                    None
                }
                Op::Finish { cycles } => {
                    if index + 1 != ir.ops.len() {
                        return Err(invalid("Finish must be terminal"));
                    }
                    inputs[0] = Some(cycles);
                    None
                }
            };
            if inputs
                .into_iter()
                .flatten()
                .any(|v| !defined.get(v.0 as usize).copied().unwrap_or(false))
            {
                return Err(invalid("SSA use before definition"));
            }
            if let Op::LoadState { field, .. } | Op::StoreState { field, .. } = *op
                && (matches!(field, StateField::Data(n) if n >= 8)
                    || matches!(field, StateField::Address(n) if n >= 7))
            {
                return Err(invalid("invalid state field"));
            }
            if let Some(value) = dst {
                let slot = defined
                    .get_mut(value.0 as usize)
                    .ok_or_else(|| invalid("SSA destination out of range"))?;
                if *slot {
                    return Err(invalid("SSA value assigned twice"));
                }
                *slot = true;
            }
        }
    }
    Ok(())
}

